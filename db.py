def settings():
    return dict(host=os.getenv('PGHOST','localhost'),port=int(os.getenv('PGPORT','5432')),
                dbname=os.getenv('PGDATABASE','signal'),user=os.getenv('PGUSER','signal'),
                password=os.getenv('PGPASSWORD',''),connect_timeout=int(os.getenv('PGCONNECT_TIMEOUT','10')))


def schema():
    name=os.getenv('PGSCHEMA','public')
    if not name or len(name)>63 or any(not (c.isalnum() or c=='_') for c in name):raise ValueError('Invalid PGSCHEMA')
    return name


def lock_key(key):
    return int.from_bytes(sha256(key.encode()).digest()[:8],signed=True)


def raw_connect():
    db=psycopg.connect(**settings(),row_factory=dict_row)
    db.execute(SQL('SET search_path TO {}').format(Identifier(schema())))
    return db


def init_schema():
    key=(tuple(sorted(settings().items())),schema())
    if key in _ready:return
    with _ready_lock:
        if key in _ready:return
        with raw_connect() as db:
            db.execute('SELECT pg_advisory_xact_lock(%s)',(lock_key('schema:'+schema()),))
            db.execute(SQL('CREATE SCHEMA IF NOT EXISTS {}').format(Identifier(schema())))
            db.execute(SQL('SET search_path TO {}').format(Identifier(schema())))
            db.execute(SCHEMA)
        _ready.add(key)


@contextmanager
def connect():
    init_schema()
    db=raw_connect()
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


@contextmanager
def advisory_lock(key,blocking=True):
    init_schema()
    db=raw_connect();number=lock_key(key);acquired=False
    try:
        if blocking:db.execute('SELECT pg_advisory_lock(%s)',(number,));acquired=True
        else:
            acquired=db.execute('SELECT pg_try_advisory_lock(%s) AS acquired',(number,)).fetchone()['acquired']
            if not acquired:raise BlockingIOError
        db.commit()
        yield
    finally:
        try:
            if acquired:db.execute('SELECT pg_advisory_unlock(%s)',(number,))
            db.commit()
        except Exception:pass
        db.close()
